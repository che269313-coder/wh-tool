/* Generate the browser registry from authored per-faction package.json files. */
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const packagesDir = path.join(root, "data", "factions");
const packages = fs.readdirSync(packagesDir)
  .map((name) => path.join(packagesDir, name, "package.json"))
  .filter((file) => fs.existsSync(file))
  .map((file) => JSON.parse(fs.readFileSync(file, "utf8")))
  .sort((a, b) => a.order - b.order);

const definitions = packages.map((payload) => payload.definition);
const output = [
  "/* Generated from data/factions/<id>/package.json. Do not edit this file. */",
  "(function (root) {",
  "  const registry = root.WarhammerFactionRegistry;",
  '  if (!registry) throw new Error("faction-registry.js must load before factions.js");',
  `  const definitions = ${JSON.stringify(definitions, null, 2)};`,
  "  definitions.forEach((definition) => registry.register(definition));",
  "})(typeof globalThis === \"undefined\" ? this : globalThis);",
  "",
].join("\n");
fs.writeFileSync(path.join(root, "docs", "rules", "factions.js"), output, "utf8");
console.log(`faction registry generated: ${definitions.length} packages`);
